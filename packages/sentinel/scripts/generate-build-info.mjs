// Generate the analyzer's build identity.
//
// `analysis.engine.build_sha256` identifies the code that produced a report. It
// used to be read at runtime as the hash of report.ts's own file, which cannot
// work once the analyzer is bundled — a bundle has no source files to read. It
// is computed here instead, over every analyzer source, which is also a wider
// and more useful claim than hashing one file.
//
// Line endings are normalised before hashing so the identity is a property of
// the code, not of how the repository happened to be checked out.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const sourceRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
const GENERATED = "build-info.ts";

// `.mjs` is included so the precompiled schema validator counts: it decides
// whether a report is accepted, so it is part of what produced one. This runs
// after the validator is generated, so the hash covers what actually ships.
async function sourceFiles(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) {
      found.push(...await sourceFiles(full));
    } else if ((entry.name.endsWith(".ts") || entry.name.endsWith(".mjs")) && entry.name !== GENERATED) {
      found.push(full);
    }
  }
  return found;
}

const files = (await sourceFiles(sourceRoot)).sort((left, right) => left.localeCompare(right));
const digest = createHash("sha256");
for (const file of files) {
  const contents = (await readFile(file, "utf8")).replace(/\r\n/g, "\n");
  digest.update(relative(sourceRoot, file).replace(/\\/g, "/"));
  digest.update("\0");
  digest.update(contents);
  digest.update("\0");
}

const sha256 = digest.digest("hex");
await writeFile(join(sourceRoot, GENERATED), `// Generated by scripts/generate-build-info.mjs. Do not edit.
export const ANALYZER_BUILD_SHA256 = "${sha256}";
`, "utf8");

console.log(`build-info: ${sha256} over ${files.length} analyzer sources`);
