// Precompile the report schema into a standalone validator.
//
// ajv normally compiles a schema by generating JavaScript source and evaluating
// it. Constrained runtimes forbid that — a Worker rejects it with "Code
// generation from strings disallowed" — so the compile step happens here, at
// build time, and ships as ordinary code.
//
// The CLI and the monitor both load this one artifact. Two validators built from
// the same schema at the same build could not drift, but one artifact cannot
// drift at all.
const { createHash } = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const Ajv = require("ajv/dist/2020.js").default ?? require("ajv/dist/2020.js");
const addFormats = require("ajv-formats").default ?? require("ajv-formats");
const standalone = require("ajv/dist/standalone").default ?? require("ajv/dist/standalone");

const packageRoot = path.join(__dirname, "..");
const schemaPath = path.join(packageRoot, "schemas", "report.schema.json");
const outDirectory = path.join(packageRoot, "src", "generated");
const outPath = path.join(outDirectory, "report-validator.mjs");

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);

let source = standalone(ajv, ajv.compile(schema));

// ajv's standalone emitter still writes CommonJS `require` calls for its runtime
// helpers even in ESM mode. They are rewritten to static imports here, with the
// interop shape resolved explicitly rather than left to a bundler's default-import
// heuristic — these two modules do not present the same shape.
//
// The `.js` extensions are required: Node's ESM resolver will not infer them, and
// a bundler that tolerates their absence hides the failure until it runs on Node.
const preamble = [
  `// Generated by scripts/generate-validator.cjs from schemas/report.schema.json. Do not edit.`,
  `import * as ucs2Module from "ajv/dist/runtime/ucs2length.js";`,
  `import * as formatsModule from "ajv-formats/dist/formats.js";`,
  `const ucs2length = ucs2Module.default?.default ?? ucs2Module.default ?? ucs2Module;`,
  `const fullFormats = (formatsModule.default ?? formatsModule).fullFormats;`
].join("\n");

source = source
  .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, "ucs2length")
  .replace(/require\("ajv-formats\/dist\/formats"\)\.fullFormats/g, "fullFormats")
  .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)/g, "({default: ucs2length})")
  .replace(/require\("ajv-formats\/dist\/formats"\)/g, "({fullFormats: fullFormats})");

// A surviving require() or any eval-shaped construct would fail only at runtime,
// inside the Worker, on a real customer's package. Fail the build instead.
const unresolved = source.match(/require\([^)]*\)/g);
if (unresolved) {
  throw new Error(`generated validator still contains require(): ${[...new Set(unresolved)].join(", ")}`);
}
if (/new Function|\beval\(/.test(source)) {
  throw new Error("generated validator contains runtime code generation and will not load in a Worker");
}

const contents = `${preamble}\n${source}`;
fs.mkdirSync(outDirectory, { recursive: true });
fs.writeFileSync(outPath, contents, "utf8");

fs.writeFileSync(path.join(outDirectory, "report-validator.d.mts"), `// Generated by scripts/generate-validator.cjs. Do not edit.
import type { ErrorObject } from "ajv";

export interface CompiledValidator {
  (data: unknown): boolean;
  errors?: ErrorObject[] | null;
}

declare const validate: CompiledValidator;
export default validate;
export { validate };
`, "utf8");

const schemaSha256 = createHash("sha256").update(fs.readFileSync(schemaPath)).digest("hex");
console.log(`validator: ${(contents.length / 1024).toFixed(1)} KB from schema ${schemaSha256.slice(0, 12)}`);
